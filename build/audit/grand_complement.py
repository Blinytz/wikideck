def _corriger(lot):
    out = []
    for nom, titre in lot:
        if nom in CORRECTIONS_TITRES:
            v = CORRECTIONS_TITRES[nom]
            if v is None:
                continue
            nom, titre = v if isinstance(v, tuple) else (nom, v)
        out.append((nom, titre))
    return out


